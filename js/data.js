/** Kembalikan label kategori / sub sesuai bahasa aktif */
function catLabel(cat)         { return (typeof currentLang !== 'undefined' && currentLang === 'en') ? cat.labelEn : cat.labelId; }
function subLabel(sub)         { return (typeof currentLang !== 'undefined' && currentLang === 'en') ? sub.labelEn : sub.labelId; }

/** Kembalikan nama / deskripsi produk sesuai bahasa aktif */
function prodName(p)           { return (typeof currentLang !== 'undefined' && currentLang === 'en') ? p.nameEn : p.nameId; }
function prodDesc(p)           { return (typeof currentLang !== 'undefined' && currentLang === 'en') ? p.descEn : p.descId; }

// Alias backward-compat: kode lama yang pakai p.name / p.desc tetap bekerja
// (diset saat halaman dimuat dan setiap kali bahasa berubah)
function syncProductAliases() {
  PRODUCTS.forEach(p => {
    p.name = prodName(p);
    p.desc = prodDesc(p);
  });
  CATEGORIES.forEach(cat => {
    cat.label = catLabel(cat);
    cat.subs.forEach(sub => { sub.label = subLabel(sub); });
  });
}

// Panggil sekali saat file dimuat, lalu lagi setiap kali bahasa berubah
syncProductAliases();

// Hook ke sistem i18n: patch setLang agar sync alias
if (typeof setLang !== 'undefined') {
  const _origSetLang = setLang;
  // eslint-disable-next-line no-global-assign
  setLang = function(lang) { _origSetLang(lang); syncProductAliases(); };
}
// Jika translations.js dimuat setelah data.js, kita patch saat DOMContentLoaded
document.addEventListener('DOMContentLoaded', () => {
  // Patch setLang jika belum di-patch
  if (typeof setLang !== 'undefined' && !setLang._aliased) {
    const _orig = setLang;
    // eslint-disable-next-line no-global-assign
    setLang = function(lang) { _orig(lang); syncProductAliases(); };
    setLang._aliased = true;
  }
  // Sync sekali lagi setelah lang diinisialisasi dari localStorage
  syncProductAliases();
});

function getCategory(id)    { return CATEGORIES.find(c => c.id === id); }
function getSubcat(catId, subId) {
  const c = getCategory(catId);
  return c ? c.subs.find(s => s.id === subId) : null;
}
function getProductsByFilter(catId, subId) {
  return PRODUCTS.filter(p =>
    (!catId || p.cat === catId) &&
    (!subId || p.subcat === subId)
  );
}
