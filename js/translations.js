// ===========================
// ACTIVE LANGUAGE
// ===========================

let currentLang = localStorage.getItem('bm_lang') || 'id';

function t(key) {
  return (
    TRANSLATIONS[currentLang]?.[key] ||
    TRANSLATIONS.id[key] ||
    key
  );
}

// ===========================
// SET LANGUAGE
// ===========================

function setLang(lang) {
  if (!TRANSLATIONS[lang]) return;

  currentLang = lang;
  localStorage.setItem('bm_lang', lang);

  applyTranslations();
  updateLangButtons();

  // Notify other modules that language has changed
  document.dispatchEvent(
    new CustomEvent('langChanged', {
      detail: { lang }
    })
  );
}

// ===========================
// APPLY TRANSLATIONS
// ===========================

function applyTranslations() {
  // Text content
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const val = t(key);

    if (
      el.tagName === 'INPUT' ||
      el.tagName === 'TEXTAREA'
    ) {
      el.placeholder = val;
    } else {
      el.textContent = val;
    }
  });

  // Placeholder attributes
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.placeholder = t(
      el.getAttribute('data-i18n-placeholder')
    );
  });

  // Title attributes
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    el.title = t(
      el.getAttribute('data-i18n-title')
    );
  });

  // HTML content
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.getAttribute('data-i18n-html');
    el.innerHTML = t(key);
  });

  // Update document language
  document.documentElement.lang = currentLang;
}

// ===========================
// LANGUAGE BUTTONS
// ===========================

function updateLangButtons() {
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle(
      'active',
      btn.dataset.lang === currentLang
    );
  });
}

