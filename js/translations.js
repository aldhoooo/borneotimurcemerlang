// Active language
let currentLang = localStorage.getItem('bm_lang') || 'id';

function t(key) {
  return TRANSLATIONS[currentLang][key] || TRANSLATIONS['id'][key] || key;
}

function setLang(lang) {
  currentLang = lang;
  localStorage.setItem('bm_lang', lang);
  applyTranslations();
  updateLangButtons();
  // Notify other modules (catalog.js, data.js) that language has changed
  document.dispatchEvent(new CustomEvent('langChanged', { detail: { lang } }));
}

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const val = t(key);
    if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
      el.placeholder = val;
    } else if (el.tagName === 'OPTION') {
      el.textContent = val;
    } else {
      el.textContent = val;
    }
  });

  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
  });

  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    el.title = t(el.getAttribute('data-i18n-title'));
  });

  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    el.innerHTML = TRANSLATIONS[currentLang][el.getAttribute('data-i18n-html')] || '';
  });

  // update lang attr
  document.documentElement.lang = currentLang;
}

function updateLangButtons() {
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === currentLang);
  });
}

